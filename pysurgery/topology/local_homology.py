r"""Local homology at every simplex, and the homology-manifold certificate.

Overview:
    Everything here is computed on the COMPLEX, exactly, at every simplex: no point is
    sampled, no scale is swept, nothing is estimated. It complements
    ``SimplicialComplex.is_homology_manifold`` (which reads vertex links only) with the
    full, simplex-by-simplex certificate of the definition.

Key Concepts:
    - **Local homology from links.** For x in the open simplex sigma of dimension k,

          H_j(|K|, |K| - x)  =  H~_{j-k-1}( lk sigma )

      with reduced integer homology and the convention ``H~_{-1}(empty) = Z`` (the link
      of a maximal simplex is empty). So local homology is read off the links, and the
      links of all simplices are obtained in one pass from the maximal simplices of K:
      ``lk sigma`` is generated by ``tau - sigma`` over the maximal ``tau >= sigma``.
    - **Classification relative to a dimension n.** At an interior point of an
      n-manifold ``H_*(M, M - x) = H_*(R^n, R^n - 0)`` (Z in degree n, 0 elsewhere); at
      a boundary point it is 0. So, per simplex sigma of dimension k:

          sphere    H~_*(lk sigma) = H~_*(S^(n-k-1)) and dim(lk sigma) = n-k-1
          acyclic   H~_*(lk sigma) = 0, k < n, and lk sigma is pure of dimension n-k-1
          other     anything else -- a singular point of |K| as an n-dimensional object

      Two sheets crossing at a point, a pinch point, a branching (n-1)-face, a free
      face, a simplex of the wrong dimension: each lands where the computation puts it,
      not where a threshold does.
    - **The certificate is the definition, checked everywhere.**
      ``closed``: every simplex is ``sphere``.
      ``with boundary``: every simplex is ``sphere`` or ``acyclic``, the acyclic simplices
      form a subcomplex B, and B is itself a closed homology (n-1)-manifold (Mitchell,
      *Defining the boundary of a homology manifold*, Proc. AMS 110 (1990) -- a
      necessary condition, checked the same way). Local homology alone cannot tell a
      boundary point from the free end of a dangling edge (both have zero local
      homology), and a vertex link can have the homology of S^(n-1) without being a
      homology manifold itself -- which is why every simplex is checked and the
      boundary is checked for consistency, rather than vertex links alone.

What the certificate implies:
    - ``n <= 3``: a simplicial homology n-manifold (with boundary) is a PL n-manifold
      (with boundary). Links of simplices of a homology manifold are homology
      manifolds with sphere / acyclic homology, and in dimension <= 2 that forces the
      sphere / the disk (classification of surfaces). Recorded as
      ``implies_pl_manifold``.
    - ``n >= 4``: NOT implied. A vertex link can be a homology 3-sphere that is not S^3
      (Poincare's), and then the vertex has no Euclidean neighbourhood.

What this is not about:
    It is about |K|. Whether |K| reflects the data is the scale question
    (Niyogi-Smale-Weinberger, see ``pysurgery.geometry.scale_window``). Local homology
    is not a homotopy invariant: the nerve of a cover can have simplices above the
    ambient dimension, and then its local homology is that of the nerve, not of the
    union it is homotopy equivalent to.

Common Workflows:
    1. **Certify a mesh** -> ``certify_homology_manifold(K)`` (or
       ``K.certify_homology_manifold()``).
    2. **Locate singularities** -> ``singular_simplices(K, n)``.
    3. **Extract the boundary** -> ``homology_manifold_boundary(K, n)``.
    4. **Read local homology at a point** -> ``local_homology(K, sigma)``.

Coefficient Ring:
    Z, exactly (ranks and torsion). Julia and Python backends give identical results.
"""

