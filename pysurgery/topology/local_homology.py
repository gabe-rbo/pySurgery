def _all_simplices(K: "SimplicialComplex") -> List[Simplex]:
    return [tuple(int(v) for v in s) for d in K.dimensions for s in K.n_simplices(d)]


def maximal_simplices(K: "SimplicialComplex") -> List[Simplex]:
    """The maximal simplices (facets) of K: those that are a face of nothing larger.

    Args:
        K: A simplicial complex (closed under faces).

    Returns:
        The maximal simplices, sorted by dimension then lexicographically.
    """
    non_max = set()
    for d in K.dimensions:
        if d < 1:
            continue
        for s in K.n_simplices(d):
            for i in range(len(s)):
                non_max.add(tuple(s[:i]) + tuple(s[i + 1:]))
    return sorted((s for s in _all_simplices(K) if s not in non_max), key=lambda s: (len(s), s))


def links_of(K: "SimplicialComplex", sigmas: Iterable[Iterable[int]]) -> Dict[Simplex, List[Simplex]]:
    """The maximal simplices of ``lk(sigma)`` for every sigma, in one pass.

    What is Being Computed?:
        ``lk(sigma) = {tau - sigma : sigma <= tau in K}``; its maximal simplices are
        exactly ``tau - sigma`` for the maximal ``tau >= sigma`` (two distinct maximal
        simplices containing sigma give distinct, incomparable differences).

    Args:
        K: A simplicial complex.
        sigmas: The simplices whose links are wanted (each must be in K).

    Returns:
        ``{sigma: [maximal simplices of lk(sigma)]}``; an empty list is the empty link.

    Raises:
        ValueError: If some sigma is not a simplex of K.
    """
    targets = [tuple(sorted(int(v) for v in s)) for s in sigmas]
    present = {d: set(K.n_simplices(d)) for d in K.dimensions}
    for s in targets:
        if s not in present.get(len(s) - 1, ()):
            raise ValueError(f"{s} is not a simplex of the complex")
    by_vertex: Dict[int, List[Simplex]] = defaultdict(list)
    for tau in maximal_simplices(K):
        for v in tau:
            by_vertex[v].append(tau)
    out: Dict[Simplex, List[Simplex]] = {}
    for s in targets:
        ss = set(s)
        gens = []
        for tau in by_vertex[s[0]]:
            if ss.issubset(tau):
                rest = tuple(v for v in tau if v not in ss)
                if rest:
                    gens.append(rest)
        out[s] = gens
    return out


def _flat(simplices: Sequence[Simplex]) -> Tuple[np.ndarray, np.ndarray]:
    flat = np.fromiter((v for s in simplices for v in s), dtype=np.int64)
    offsets = np.zeros(len(simplices) + 1, dtype=np.int64)
    np.cumsum([len(s) for s in simplices], out=offsets[1:])
    return flat, offsets


def _link_data(
    K: "SimplicialComplex", targets: List[Simplex], backend: str
) -> Dict[Simplex, Tuple[ReducedHomology, int, bool]]:
    """Reduced homology, dimension and purity of every target's link."""
    backend_norm = str(backend).lower().strip()
    use_julia = backend_norm == "julia" or (backend_norm == "auto" and julia_engine.available)
    if use_julia and targets:
        try:
            flat, offsets = _flat(_all_simplices(K))
            tflat, toffsets = _flat(targets)
            res = julia_engine.classify_simplex_links(flat, offsets, tflat, toffsets)
            return dict(zip(targets, res))
        except Exception as e:  # pragma: no cover - depends on the Julia runtime
            if backend_norm == "julia":
                raise
            warnings.warn(f"Julia link classification failed ({e!r}); falling back to Python.")
    links = links_of(K, targets)
    out = {}
    for s in targets:
        gens = links[s]
        red, ldim = reduced_homology_from_simplices(gens)
        pure = all(len(g) - 1 == ldim for g in gens)
        out[s] = (red, ldim, pure)
    return out


def link_reduced_homology(
    K: "SimplicialComplex", sigma: Iterable[int], backend: str = "auto"
) -> ReducedHomology:
    """Reduced integer homology of ``lk(sigma)``, degree -1 included.

    Args:
        K: A simplicial complex.
        sigma: A simplex of K.
        backend: 'auto', 'julia' or 'python'.

    Returns:
        ``{degree: (rank, torsion)}`` for the nonzero groups; ``{-1: (1, [])}`` when
        sigma is maximal (empty link).
    """
    s = tuple(sorted(int(v) for v in sigma))
    return _link_data(K, [s], backend)[s][0]


def local_homology(
    K: "SimplicialComplex", sigma: Iterable[int], backend: str = "auto"
) -> ReducedHomology:
    """Local homology ``H_j(|K|, |K| - x)`` for x in the open simplex sigma, exactly.

    What is Being Computed?:
        ``H_j(|K|, |K| - x) = H~_{j-k-1}(lk sigma)``, k = dim sigma (Munkres,
        *Elements of Algebraic Topology*, Lemma 63.1).

    Args:
        K: A simplicial complex.
        sigma: A simplex of K.
        backend: 'auto', 'julia' or 'python'.

    Returns:
        ``{j: (rank, torsion)}`` for the nonzero groups.

    Example:
        >>> # interior point of a triangulated surface: Z in degree 2
        >>> local_homology(sphere, (0,))
        {2: (1, [])}
    """
    s = tuple(sorted(int(v) for v in sigma))
    k = len(s) - 1
    return {d + k + 1: (r, list(t)) for d, (r, t) in link_reduced_homology(K, s, backend).items()}


