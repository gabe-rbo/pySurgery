class LocalHomologyType(BaseModel):
    """The local type of |K| at the points of one open simplex, relative to a dimension n.

    Attributes:
        simplex (tuple[int, ...]): The simplex (sorted vertex tuple).
        dim (int): Its dimension k.
        kind (str): ``"sphere"`` (interior point of a homology n-manifold),
            ``"acyclic"`` (boundary candidate) or ``"other"`` (singular) -- see the module
            docstring for the exact rule.
        link_reduced_homology (dict[int, tuple[int, list[int]]]): The nonzero reduced
            integer homology of ``lk(simplex)``, ``{degree: (rank, torsion)}``; degree -1
            appears exactly for the empty link.
        link_dimension (int): ``dim lk(simplex)`` (-1 for the empty link).
        link_pure (bool): Whether every maximal simplex of the link has dimension
            ``link_dimension``.
    """

    model_config = ConfigDict(frozen=True)

    simplex: Tuple[int, ...]
    dim: int
    kind: str
    link_reduced_homology: Dict[int, Tuple[int, List[int]]]
    link_dimension: int
    link_pure: bool

    def local_homology(self) -> ReducedHomology:
        """``H_j(|K|, |K| - x)`` for x in this open simplex, ``{j: (rank, torsion)}``.

        Returns:
            The nonzero local homology groups, shifted from the link's reduced homology by
            ``j = degree + dim + 1``.
        """
        return {d + self.dim + 1: (r, list(t)) for d, (r, t) in self.link_reduced_homology.items()}

    def __str__(self) -> str:
        lk = ", ".join(
            f"H~_{d}=" + ("Z^%d" % r if r else "0") + "".join(f"+Z/{t}" for t in tor)
            for d, (r, tor) in sorted(self.link_reduced_homology.items())
        ) or "acyclic"
        return f"{self.simplex} (dim {self.dim}): {self.kind}; link {lk}"


class PseudomanifoldReport(BaseModel):
    """The combinatorial pseudomanifold conditions at dimension n.

    Attributes:
        n (int): The dimension tested.
        pure (bool): K has dimension n and every simplex lies in an n-simplex.
        non_branching (bool): Every (n-1)-simplex lies in at most two n-simplices.
        strongly_connected (bool): The dual graph (n-simplices, adjacent across
            (n-1)-faces) is connected.
        n_top (int): Number of n-simplices.
        n_boundary_faces (int): (n-1)-simplices in exactly one n-simplex.
        max_cofacets (int): Largest number of n-simplices around one (n-1)-simplex.
        reason (str): Why the test could not run (empty when it did).
    """

    n: int
    pure: bool
    non_branching: bool
    strongly_connected: bool
    n_top: int
    n_boundary_faces: int
    max_cofacets: int
    reason: str = ""

    @property
    def is_pseudomanifold(self) -> bool:
        """Pure, non-branching and strongly connected."""
        return bool(self.pure and self.non_branching and self.strongly_connected)

    @property
    def is_closed_pseudomanifold(self) -> bool:
        """A pseudomanifold with no boundary (n-1)-faces."""
        return self.is_pseudomanifold and self.n_boundary_faces == 0


class HomologyManifoldCertificate(BaseModel):
    """Result of ``certify_homology_manifold``: the definition, checked at every simplex.

    Attributes:
        n (int): The dimension certified against.
        is_closed_homology_manifold (bool): Every simplex has a sphere link.
        is_homology_manifold_with_boundary (bool): Every simplex is sphere or acyclic, the
            acyclic simplices form a subcomplex, and that subcomplex is a closed homology
            (n-1)-manifold. True also for closed manifolds (empty boundary).
        implies_pl_manifold (bool): ``n <= 3`` and one of the above -- then |K| is a PL
            n-manifold (with boundary).
        n_simplices (int): Number of simplices checked (all of them).
        n_sphere (int): Simplices with sphere links.
        n_acyclic (int): Simplices with acyclic links of the right dimension.
        n_other (int): Singular simplices.
        singular (list[LocalHomologyType]): Where the certificate fails.
        boundary (list[tuple[int, ...]]): The acyclic simplices.
        pseudomanifold (PseudomanifoldReport): The combinatorial conditions.
        notes (list[str]): Human-readable reasons for every failure.
        exact (bool): Always True -- integer homology of every link.
    """

    model_config = ConfigDict(arbitrary_types_allowed=True)

    n: int
    is_closed_homology_manifold: bool
    is_homology_manifold_with_boundary: bool
    implies_pl_manifold: bool
    n_simplices: int
    n_sphere: int
    n_acyclic: int
    n_other: int
    singular: List[LocalHomologyType] = Field(default_factory=list)
    boundary: List[Tuple[int, ...]] = Field(default_factory=list)
    pseudomanifold: Optional[PseudomanifoldReport] = None
    notes: List[str] = Field(default_factory=list)
    exact: bool = True

    @property
    def singular_vertices(self) -> List[int]:
        """Vertices whose own link is singular."""
        return [t.simplex[0] for t in self.singular if t.dim == 0]

    def __str__(self) -> str:
        if self.is_closed_homology_manifold:
            head = f"closed homology {self.n}-manifold"
        elif self.is_homology_manifold_with_boundary:
            head = (
                f"homology {self.n}-manifold WITH boundary "
                f"({len(self.boundary)} boundary simplices)"
            )
        else:
            head = f"NOT a homology {self.n}-manifold ({len(self.singular)} singular simplices)"
        tail = " -- hence a PL manifold (n <= 3)" if self.implies_pl_manifold else ""
        return (
            f"[n={self.n}] {head}{tail}; checked all {self.n_simplices} simplices"
            + "".join("\n  " + s for s in self.notes)
        )


